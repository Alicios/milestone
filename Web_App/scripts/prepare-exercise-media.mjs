import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises'
import { resolve, dirname, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sources = JSON.parse(await readFile(resolve(root, 'src/data/exerciseMedia.json'), 'utf8'))
const previews = JSON.parse(await readFile(resolve(root, 'src/data/exerciseVideoPreviews.json'), 'utf8'))
const result = Object.entries(sources).map(([name, entries]) => ({ name, media: entries.map((entry) => {
  let preview = previews[entry.url]
  if (!preview && entry.kind === 'video-link') {
    const url = new URL(entry.url)
    if (url.hostname === 'www.youtube.com') {
      const target = new URL(`https://www.youtube-nocookie.com/embed/${url.searchParams.get('v')}`)
      if (url.searchParams.has('t')) target.searchParams.set('start', url.searchParams.get('t'))
      target.searchParams.set('playsinline', '1')
      preview = { kind: 'embed', url: target.href }
    }
  }
  if (preview && !preview.poster && preview.url.includes('youtube-nocookie.com/embed/')) {
    preview = { ...preview, poster: `https://i.ytimg.com/vi/${new URL(preview.url).pathname.split('/')[2]}/hqdefault.jpg` }
  }
  if (entry.kind === 'video-link' && !preview) throw new Error(`Missing video player: ${name}`)
  const replacement = entry.source === 'PocketPhysio' && preview?.sourceUrl && preview.source
  return { ...entry, ...(preview ? { preview } : {}), ...(replacement ? { url: preview.sourceUrl, source: preview.source, accessNote: undefined } : {}) }
}) }))
await mkdir(resolve(root, 'test-results/patient-media'), { recursive: true })
await writeFile(resolve(root, 'test-results/patient-media/catalog.json'), JSON.stringify(result, null, 2) + '\n')
// Seed by exact unique catalog name, never by copied database UUIDs.
const payload = JSON.stringify(result)
if (payload.includes('$exercise_media$')) throw new Error('Unexpected SQL delimiter')
const sql = `with seed as (select * from jsonb_to_recordset($exercise_media$${payload}$exercise_media$::jsonb) as x(name text, media jsonb)), matched as (select min(e.id::text)::uuid as exercise_id, s.media from seed s join public.exercises e on e.name=s.name group by s.name,s.media having count(*)=1) insert into public.exercise_media(exercise_id,media) select exercise_id,media from matched on conflict(exercise_id) do update set media=excluded.media,updated_at=now();\n`
await writeFile(resolve(root, 'test-results/patient-media/seed.sql'), sql)
await writeFile(resolve(root, 'supabase/seed_exercise_media.sql'), '-- Generated by scripts/prepare-exercise-media.mjs from the approved media manifests.\n' + sql)
if (process.argv.includes('--sync-mobile-assets')) {
  const target = resolve(root, '../Mobile_App/milestone')
  const assets = [...new Set(result.flatMap((exercise) => exercise.media.filter((item) => item.url.startsWith('/exercise-media/')).map((item) => item.url)))].sort()
  const registry = []
  for (const url of assets) {
    const source = resolve(root, 'public' + url)
    const destination = resolve(target, 'assets' + url)
    if (relative(target, destination).startsWith('..')) throw new Error('Asset path outside the patient app')
    await mkdir(dirname(destination), { recursive: true })
    await copyFile(source, destination)
    registry.push(`  ${JSON.stringify(url)}: require(${JSON.stringify('../assets' + url)}),`)
  }
  await writeFile(resolve(target, 'lib/exerciseMediaAssets.js'), `// Generated by Web_App/scripts/prepare-exercise-media.mjs --sync-mobile-assets.\nexport default {\n${registry.join('\n')}\n};\n`)
  console.log(`Synced ${assets.length} approved illustrations to the patient app.`)
}
console.log(`Prepared ${result.length} exercise media records (${createHash('sha256').update(payload).digest('hex').slice(0, 12)}).`)
