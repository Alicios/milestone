import { test, expect } from '@playwright/test'
import { setup, patient, profile, routineA } from './fixture.mjs'

for (const width of [390, 1365]) for (const theme of ['light', 'dark']) {
  test(`weekly and monthly patient calendar at ${width}px ${theme}`, async ({ context, page }) => {
    await page.setViewportSize({ width, height: 1000 })
    const state = await setup(context, { assignments: [
      { id: 'month-history', patient_profile_id: profile, routine_id: routineA, scheduled_date: '2026-10-02', status: 'completed', routine_name_snapshot: 'Earlier month routine' },
      { id: 'cancelled', patient_profile_id: profile, routine_id: routineA, scheduled_date: '2026-10-03', status: 'cancelled', routine_name_snapshot: 'Cancelled routine' },
    ], foreignDates: ['2026-10-21'] })
    await page.goto('/dashboard/settings')
    await page.getByRole('radio', { name: theme === 'dark' ? 'Dark' : 'Light', exact: true }).check()
    await page.evaluate(path => { history.pushState({}, '', path); dispatchEvent(new PopStateEvent('popstate')) }, `/dashboard/patients/${patient}`)
    const week = page.getByRole('region', { name: 'Weekly calendar for Synthetic Browser Patient', exact: true })
    await expect(week).toBeVisible()
    await expect(page.getByRole('button', { name: 'Weekly', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await page.getByRole('button', { name: 'Monthly', exact: true }).click()
    const month = page.getByRole('region', { name: 'Monthly calendar for Synthetic Browser Patient', exact: true })
    await expect(month).toBeVisible()
    await expect(month.getByRole('heading', { name: 'October 2026' })).toBeVisible()
    await expect(month.locator('tbody tr')).toHaveCount(5)
    await expect(month.getByRole('button', { name: /View assigned routine Earlier month routine/ })).toBeVisible()
    expect(state.reads.some(query => query.includes('gte.2026-09-28') && query.includes('lte.2026-11-01'))).toBe(true)
    await expect(month.getByText('Cancelled routine', { exact: true })).toHaveCount(0)
    await month.getByRole('button', { name: /View assigned routine Earlier month routine/ }).click()
    await expect(page.locator('#patient-assignment-details').getByText('Earlier month routine', { exact: true })).toBeVisible()
    await expect(page.locator('#patient-assignment-details').getByText('Friday, Oct 2', { exact: true })).toBeVisible()
    await expect(month.getByRole('cell', { name: 'Wednesday, October 21, 2026', exact: true }).getByText('Occupied')).toBeVisible()
    await expect(month.getByRole('cell', { name: 'Friday, October 2, 2026', exact: true }).getByRole('button', { name: /Assign routine/ })).toHaveCount(0)
    const scroller = month.getByRole('region', { name: /Month days and routines/ })
    await scroller.evaluate(el => { el.scrollLeft = 0 })
    await month.getByRole('button', { name: 'Assign routine to Synthetic Browser Patient on October 20, 2026', exact: true }).click()
    await expect(page.getByRole('dialog')).toBeVisible()
    await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click()
    expect(state.writes).toHaveLength(0)
    await month.getByRole('button', { name: 'Next calendar month' }).click()
    await expect(month.getByRole('heading', { name: 'November 2026' })).toBeVisible()
    await expect(month.locator('tbody tr')).toHaveCount(6)
    await expect(month.getByRole('button', { name: 'Assign routine to Synthetic Browser Patient on November 10, 2026', exact: true })).toBeDisabled()
    await month.getByRole('button', { name: 'This month', exact: true }).click()
    await expect(month.getByRole('heading', { name: 'October 2026' })).toBeVisible()
    await expect(month.getByRole('button', { name: /View assigned routine Earlier month routine/ })).toBeVisible()
    await scroller.evaluate(el => { el.scrollLeft = 0 })
    await month.scrollIntoViewIfNeeded()
    await month.screenshot({ path: `test-results/monthly-${width}-${theme}.png` })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('button', { name: 'Weekly', exact: true }).click()
    await expect(week).toBeVisible()
    await expect(week.getByRole('columnheader', { name: /Tuesday, October 20, 2026/ })).toBeVisible()
    await expect(week.getByText('Earlier month routine', { exact: true })).toHaveCount(0)
    await page.getByRole('link', { name: 'Back to Patients', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Patients', exact: true })).toBeVisible()
  })
}

test('month navigation handles leap day and year boundaries using calendar dates', async ({ context, page }) => {
  await setup(context)
  await context.route('**/rest/v1/rpc/get_routine_scheduling_policy', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ today: '2028-02-29', lastDate: '2028-03-13', horizonDays: 14, timeZone: 'America/Los_Angeles' }) }))
  await page.goto(`/dashboard/patients/${patient}`)
  await page.getByRole('button', { name: 'Monthly', exact: true }).click()
  const month = page.getByRole('region', { name: 'Monthly calendar for Synthetic Browser Patient', exact: true })
  await expect(month.getByRole('heading', { name: 'February 2028' })).toBeVisible()
  await expect(month.getByRole('cell', { name: 'Tuesday, February 29, 2028', exact: true })).toHaveAttribute('aria-current', 'date')
  await month.getByRole('button', { name: 'Previous calendar month' }).click()
  await expect(month.getByRole('heading', { name: 'January 2028' })).toBeVisible()
  await month.getByRole('button', { name: 'Previous calendar month' }).click()
  await expect(month.getByRole('heading', { name: 'December 2027' })).toBeVisible()
  await month.getByRole('button', { name: 'Next calendar month' }).click()
  await expect(month.getByRole('heading', { name: 'January 2028' })).toBeVisible()
})
