import { test, expect } from '@playwright/test'
import { setup, patient, profile } from './fixture.mjs'

async function center(page, locator, action = 'click') {
  const box = await locator.boundingBox()
  await page.mouse[action](box.x + box.width / 2, box.y + box.height / 2)
}

for (const width of [320, 390, 768, 1365]) {
  test(`patient row hit areas, hover, keyboard and layout at ${width}px`, async ({ context, page }, info) => {
    await page.setViewportSize({ width, height: 900 })
    await setup(context)
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/dashboard/patients')
    const name = page.getByRole('link', { name: 'Synthetic Browser Patient', exact: true })
    const toggle = page.getByRole('button', { name: /weekly routines for Synthetic Browser Patient/ })
    const avatar = page.getByRole('img', { name: 'Synthetic Browser Patient profile picture placeholder' })
    await expect(name).toBeVisible()
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    const panel = page.locator(`[id="${await toggle.getAttribute('aria-controls')}"]`)
    await expect(panel).toBeHidden()
    await center(page, avatar, 'move')
    await expect(name).toHaveCSS('text-decoration-line', 'none')
    await expect(toggle).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
    await name.hover()
    await expect(name).toHaveCSS('text-decoration-line', 'underline')
    await expect(name).toHaveCSS('background-color', 'rgb(130, 189, 181)')
    await expect(toggle).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
    await center(page, avatar)
    await expect(toggle).toHaveAttribute('aria-expanded', 'true')
    await expect(panel).toBeVisible()
    await expect(page).toHaveURL(/\/dashboard\/patients$/)
    await toggle.locator('svg').click()
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    // Empty space below the text remains part of the toggle, even on wrapped rows.
    await toggle.click({ position: { x: 8, y: 8 } })
    await expect(toggle).toHaveAttribute('aria-expanded', 'true')
    await page.keyboard.press('Tab')
    await expect(name).toBeFocused()
    await page.keyboard.press('Shift+Tab')
    await expect(toggle).toBeFocused()
    await page.keyboard.press('Space')
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    await expect(toggle).toHaveCSS('outline-style', 'solid')
    await page.keyboard.press('Enter')
    await expect(toggle).toHaveAttribute('aria-expanded', 'true')
    await page.keyboard.press('Tab')
    await expect(name).toBeFocused()
    await expect(name).toHaveCSS('outline-style', 'solid')
    await page.keyboard.press('Shift+Tab')
    await expect(toggle).toBeFocused()
    await page.keyboard.press('Tab')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const nameBox = await name.boundingBox()
    const arrowBox = await toggle.locator('svg').boundingBox()
    expect(nameBox.x + nameBox.width).toBeLessThan(arrowBox.x)
    await page.screenshot({ path: info.outputPath(`patient-row-${width}.png`), fullPage: true })
    await page.keyboard.press('Enter')
    await expect(page).toHaveURL(new RegExp(`/dashboard/patients/${patient}$`))
    await page.goto('/dashboard/patients')
    await name.click()
    await expect(page).toHaveURL(new RegExp(`/dashboard/patients/${patient}$`))
    expect(errors).toEqual([])
  })
}

test('long archived name wraps; discharge text toggles rather than navigates', async ({ context, page }, info) => {
  await page.setViewportSize({ width: 320, height: 900 })
  await setup(context)
  const longName = 'AlexandriaVeryLongUnbrokenName Montgomery Richardson'
  await context.route('**/rest/v1/patients?*', route => route.fulfill({ json: [{ id: patient, name: longName, care_status: 'active' }] }))
  await context.route('**/rest/v1/provider_patient_profiles?*', route => route.fulfill({ json: [{ id: profile, patient_id: patient, discharged_at: '2026-11-08T12:00:00Z', retention_ends_at: '2027-05-08T12:00:00Z' }] }))
  await page.goto('/dashboard/patients')
  await page.getByRole('button', { name: 'Archive', exact: true }).click()
  const name = page.getByRole('link', { name: longName, exact: true })
  const toggle = page.getByRole('button', { name: /weekly routines for/ })
  await expect(name).toBeVisible()
  await center(page, page.getByText(/^Discharged \d/))
  await expect(toggle).toHaveAttribute('aria-expanded', 'true')
  await expect(page).toHaveURL(/\/dashboard\/patients$/)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('long-archived-name-320.png'), fullPage: true })
})
