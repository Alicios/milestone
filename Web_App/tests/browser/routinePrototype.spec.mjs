import { test, expect } from '@playwright/test'
import { setup, routineA, routineB } from './fixture.mjs'
import { routineTemplates } from '../../src/lib/routinePrototype.ts'
import { readFileSync } from 'node:fs'
import { publicVideoPreview } from '../../src/lib/videoPreview.ts'

const mediaManifest = JSON.parse(readFileSync(new URL('../../src/data/exerciseMedia.json', import.meta.url), 'utf8'))
const names = [...new Set([...routineTemplates.flatMap((template) => template.names), ...Object.keys(mediaManifest)])]
const catalog = [...names, ...Array.from({ length: 510 - names.length }, (_, i) => `Additional catalog exercise ${String(i).padStart(3, '0')}`)]
  .sort().map((name, i) => ({ id: `00000000-0000-0000-0001-${String(i).padStart(12, '0')}`, name, desc: `Stored instructions for ${name}.` }))

test('public video previews preserve start times and private Vimeo hashes and reject unsupported links', () => {
  expect(publicVideoPreview('https://www.youtube.com/watch?v=gWKT0jXnzac&t=5m50s')).toEqual({ kind: 'embed', url: 'https://www.youtube-nocookie.com/embed/gWKT0jXnzac?start=350&playsinline=1' })
  expect(publicVideoPreview('https://youtu.be/gWKT0jXnzac?t=350')?.url).toContain('start=350')
  expect(publicVideoPreview('https://vimeo.com/123456789/abcdef1234')).toEqual({ kind: 'embed', url: 'https://player.vimeo.com/video/123456789?h=abcdef1234' })
  for (const url of ['not a URL','http://youtu.be/gWKT0jXnzac','https://youtube.com.evil.invalid/watch?v=gWKT0jXnzac','https://youtube.com/watch?v=bad','https://vimeo.com/channels/example','https://pocketphysio.app/exercises/pendulum-exercise/']) expect(publicVideoPreview(url)).toBeUndefined()
})

for (const width of [390, 1365]) {
  test(`advanced prototype loads catalog, edits locally, and shows review sources at ${width}px`, async ({ browser }, testInfo) => {
    const context = await browser.newContext({ viewport: { width, height: 900 } })
    await setup(context, { routines: [
      { id: routineA, name: 'Provider Recovery', exercise_list: [{ exercise_id: catalog[0].id, name: catalog[0].name, sets: 3, reps: 12, duration_seconds: 30, notes: 'Saved provider notes' }] },
      { id: routineB, name: 'Shoulder Mobility', exercise_list: [{ exercise_id: catalog[1].id, name: catalog[1].name }] },
    ] })
    const offsets = []; const writes = []; const errors = []
    let failCatalog = true
    await context.route('**/rest/v1/exercises?*', (route) => {
      if (failCatalog) return route.fulfill({ status: 403, json: { code: '42501', message: 'Catalog access denied' } })
      const url = new URL(route.request().url())
      const offset = Number(url.searchParams.get('offset') || 0)
      const limit = Number(url.searchParams.get('limit') || 500)
      offsets.push(offset)
      return route.fulfill({ json: catalog.slice(offset, offset + limit) })
    })
    context.on('request', (request) => {
      const readRpc = /\/rpc\/(get_routine_scheduling_policy|get_patient_schedule_occupancy)$/.test(new URL(request.url()).pathname)
      if (request.url().includes('/rest/') && request.method() !== 'GET' && !readRpc) writes.push(request.url())
    })
    const page = await context.newPage()
    // Local player document tests the embed integration without depending on YouTube availability.
    await context.route('https://www.youtube-nocookie.com/embed/**', (route) => route.fulfill({ contentType: 'text/html', body: '<!doctype html><button>Fixture video player</button>' }))
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto('/dashboard/routines')
    await page.getByRole('button', { name: 'Advanced editor', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Retry catalog' })).toBeVisible()
    failCatalog = false
    await page.getByRole('button', { name: 'Retry catalog' }).click()
    await expect(page.getByText(/510 database exercises/)).toBeVisible()
    expect(offsets).toContain(500)
    await expect(page.getByText(/14 prototype routines/)).toBeVisible()
    await expect(page.getByText(/2 provider routines/)).toBeVisible()
    await expect(page.getByText('Provider routine', { exact: true })).toHaveCount(2)
    await expect(page.getByRole('button', { name: /^Shoulder Mobility/ })).toHaveCount(2)
    await expect(page.getByRole('heading', { name: 'Shoulder Mobility', exact: true })).toBeVisible()
    await expect(page.getByText('Stored instructions for Shoulder Pendulum.', { exact: true })).toBeVisible()
    await expect(page.getByRole('link', { name: /Watch demonstration|View exercise pictures/ })).toHaveCount(1)
    await expect(page.getByRole('heading', { name: /^Routine (media|pictures and videos)$/ })).toHaveCount(0)
    await expect(page.locator('iframe')).toHaveCount(0)
    await page.getByRole('button', { name: 'Play video preview: Shoulder flexion table slide', exact: true }).click()
    const player = page.locator('iframe')
    await expect(player).toHaveAttribute('src', 'https://www.youtube-nocookie.com/embed/DRzwURt6jPk?playsinline=1&autoplay=1')
    await expect(page.frameLocator('iframe').getByRole('button', { name: 'Fixture video player' })).toBeVisible()
    expect((await player.boundingBox()).height).toBeGreaterThanOrEqual(200)
    await page.screenshot({ path: testInfo.outputPath(`video-preview-${width}.png`), fullPage: true })
    await page.getByRole('button', { name: 'Close preview', exact: true }).click()
    await expect(player).toHaveCount(0)
    await page.screenshot({ path: testInfo.outputPath(`prototype-${width}.png`), fullPage: true })
    await page.getByRole('button', { name: /^Provider Recovery/ }).click()
    await expect(page.getByRole('heading', { name: 'Provider Recovery', exact: true })).toBeVisible()
    await expect(page.getByText(`Stored instructions for ${catalog[0].name}.`, { exact: true })).toBeVisible()
    await expect(page.getByText('3 sets · 12 reps · 30 sec duration', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Edit', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Routine pictures and videos', exact: true })).toHaveCount(0)
    await expect(page.getByLabel('Sets', { exact: true })).toHaveValue('3')
    await expect(page.getByLabel('Repetitions', { exact: true })).toHaveValue('12')
    await expect(page.getByLabel('Duration (seconds)', { exact: true })).toHaveValue('30')
    await expect(page.getByLabel('Provider notes', { exact: true })).toHaveValue('Saved provider notes')
    await page.getByLabel('Routine name', { exact: false }).fill('Provider Recovery Preview')
    await page.getByRole('button', { name: 'Save changes', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Provider Recovery Preview', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Archive', exact: true }).click()
    await expect(page.getByRole('button', { name: /^Provider Recovery/ })).toHaveCount(0)
    const picker = page.getByRole('combobox', { name: 'Find a database exercise' })
    await picker.fill('Wrist Extensor Stretch')
    await page.getByRole('option', { name: 'Wrist Extensor Stretch', exact: true }).click()
    await expect(page.getByText('Stored instructions for Wrist Extensor Stretch.', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Start routine with exercise' }).click()
    await expect(page.getByLabel('Exercise name', { exact: false })).toHaveValue('Wrist Extensor Stretch')
    await expect(page.getByLabel('Sets', { exact: true })).toHaveValue('')
    await page.getByLabel('Routine name', { exact: false }).fill('Local catalog routine')
    await picker.fill('Ankle Pumps')
    await page.getByRole('option', { name: 'Ankle Pumps', exact: true }).click()
    await page.getByRole('button', { name: 'Add to routine', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Exercise 2', exact: true })).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath(`prototype-edit-${width}.png`), fullPage: true })
    expect(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)).toBe(false)
    await page.getByRole('button', { name: 'Save changes', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Local catalog routine', exact: true })).toBeVisible()
    expect(writes).toEqual([])
    await page.reload()
    await page.getByRole('button', { name: 'Advanced editor', exact: true }).click()
    await expect(page.getByText(/14 prototype routines/)).toBeVisible()
    await expect(page.getByRole('button', { name: /^Provider Recovery/ })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Local catalog routine', exact: true })).toHaveCount(0)
    await picker.fill('Walking While Carrying an Object')
    await page.getByRole('option', { name: 'Walking While Carrying an Object', exact: true }).click()
    const illustration = page.getByRole('img', { name: 'Walking While Carrying an Object', exact: true })
    await expect(illustration).toBeVisible()
    await expect(illustration).toHaveJSProperty('complete', true)
    expect(await illustration.evaluate((image) => image.naturalWidth)).toBeGreaterThan(0)
    await page.screenshot({ path: testInfo.outputPath(`exercise-illustration-${width}.png`), fullPage: true })
    const coverage = await page.evaluate(async () => {
      const { catalogExercise, providerPrototypeRoutines, buildPrototypeRoutines } = await import('/src/lib/routinePrototype.ts')
      const { default: manifest } = await import('/src/data/exerciseMedia.json')
      const catalog = Object.keys(manifest).map((name, index) => ({ id: String(index), name, description: 'Catalog instructions' }))
      const missing = catalog.filter((entry) => !catalogExercise(entry).media.length).map((entry) => entry.name)
      const templates = buildPrototypeRoutines(catalog).routines
      const provider = providerPrototypeRoutines([{ id: 'existing', name: 'Saved provider routine', exercises: catalog.map((entry, position) => ({ id: String(position), name: entry.name, exerciseId: entry.id, position })) }], catalog)
      return { count: catalog.length, missing, providerMissing: provider[0].exercises.filter((entry) => !entry.media.length).length,
        notInline: catalog.filter((entry) => !catalogExercise(entry).media.some((item) => item.kind === 'image' || item.preview)).map((entry) => entry.name),
        routineMedia: [...templates, ...provider].some((routine) => 'media' in routine),
        localImages: Object.values(manifest).flat().filter((item) => item.kind === 'image' && item.url.startsWith('/')).map((item) => item.url) }
    })
    expect(coverage.count).toBe(248)
    expect(coverage.missing).toEqual([])
    expect(coverage.providerMissing).toBe(0)
    expect(coverage.notInline).toEqual([])
    expect(coverage.routineMedia).toBe(false)
    for (const path of coverage.localImages) {
      const response = await page.request.get(path)
      expect(response.status()).toBe(200)
      expect(response.headers()['content-type']).toContain('image/png')
    }
    const catalogCard = page.getByRole('heading', { name: 'Exercise catalog', exact: true }).locator('..')
    await picker.fill('Bird Dog')
    await page.getByRole('option', { name: 'Bird Dog', exact: true }).click()
    await expect(catalogCard.getByRole('link', { name: 'Watch demonstration' })).toHaveAttribute('href', 'https://www.rehabhero.ca/exercise/bird-dog')
    await expect(catalogCard.getByText('20 free video views per month', { exact: false })).toHaveCount(0)
    await catalogCard.getByRole('button', { name: /^Play video preview:/ }).click()
    await expect(catalogCard.locator('iframe')).toHaveAttribute('src', /youtube-nocookie.com\/embed\//)
    await picker.fill('Shoulder Pendulum')
    await page.getByRole('option', { name: 'Shoulder Pendulum', exact: true }).click()
    await expect(catalogCard.locator('iframe')).toHaveCount(0)
    await expect(catalogCard.getByRole('button', { name: /^Play video preview:/ })).toHaveCount(0)
    await expect(catalogCard.getByText('Pendulum exercise for the shoulder', { exact: true })).toBeVisible()
    await expect(catalogCard.getByRole('link', { name: 'Watch demonstration' })).toHaveCount(0)
    await expect(catalogCard.getByRole('link', { name: 'Picture source' })).toHaveAttribute('href', 'https://pocketphysio.app/exercises/pendulum-exercise/')
    await picker.fill('Quadriceps Set')
    await page.getByRole('option', { name: 'Quadriceps Set', exact: true }).click()
    await catalogCard.getByRole('button', { name: /^Play video preview:/ }).click()
    // The fixture deliberately blocks external media; a native playback error must leave a usable source link.
    await expect(catalogCard.getByText('Video could not be played. Open the video source below.')).toBeVisible()
    await expect(catalogCard.getByRole('link', { name: 'Watch demonstration' })).toBeVisible()
    await catalogCard.getByRole('button', { name: 'Close preview', exact: true }).click()
    await expect(catalogCard.getByRole('button', { name: /^Play video preview:/ })).toBeVisible()
    await picker.fill('Leg Press')
    await page.getByRole('option', { name: 'Leg Press', exact: true }).click()
    const replacementPicture = catalogCard.getByRole('img', { name: 'Leg Press', exact: true })
    await expect(replacementPicture).toBeVisible()
    await expect(replacementPicture).toHaveJSProperty('complete', true)
    expect(await replacementPicture.evaluate((image) => image.naturalWidth)).toBeGreaterThan(0)
    await expect(catalogCard.getByRole('button', { name: /^Play video preview:/ })).toHaveCount(0)
    await page.screenshot({ path: testInfo.outputPath(`picture-replacement-${width}.png`), fullPage: true })
    expect(errors).toEqual([])
    await context.close()
  })
}
