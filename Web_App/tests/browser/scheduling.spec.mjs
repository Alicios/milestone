import { test, expect } from '@playwright/test'
import { setup, patient, routineA, routineB, profile } from './fixture.mjs'

const path = `/dashboard/patients/${patient}`
async function select(page, weekday, routine) {
  await page.getByRole('combobox', { name: weekday, exact: true }).click()
  await page.getByRole('option', { name: routine, exact: true }).click()
}
async function previewTuesday(page) {
  await page.getByRole('button', { name: 'Schedule week', exact: true }).click()
  await select(page, 'Tuesday', 'Catalog A')
  await page.getByRole('button', { name: 'Preview schedule', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Preview · 1 assignment', exact: true })).toBeVisible()
}
test('patient workflow previews different weekday prescriptions and finite repetition; rest days create no writes', async ({ context, page }) => {
  const state = await setup(context); await page.goto(path)
  await page.getByRole('button', { name: 'Schedule week', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Preview schedule' })).toBeDisabled()
  await select(page, 'Tuesday', 'Catalog A'); await select(page, 'Wednesday', 'Catalog B')
  await page.getByLabel('Repeat weekly through the remaining scheduling window').check()
  await page.getByRole('button', { name: 'Preview schedule', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Preview · 4 assignments' })).toBeVisible()
  await expect(page.getByText('Move slowly', { exact: true })).toHaveCount(2)
  await expect(page.getByText(/3 sets.*12 reps.*30/)).toHaveCount(2)
  expect(state.writes).toHaveLength(0)
  await page.getByRole('button', { name: 'Confirm schedule', exact: true }).dblclick()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(state.writes).toHaveLength(1)
  expect(state.writes[0].p_entries.map((e) => [e.date, e.routineId])).toEqual([['2026-10-20', routineA], ['2026-10-21', routineB], ['2026-10-27', routineA], ['2026-10-28', routineB]])
  await page.getByRole('button', { name: 'Next calendar week' }).click()
  await expect(page.getByText('Catalog A', { exact: true })).toBeVisible()
  await page.reload(); await expect(page.getByText('Catalog A', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Next calendar week' }).click()
  await page.getByRole('button', { name: 'Next calendar week' }).click()
  await page.getByRole('button', { name: 'Next calendar week' }).click()
  await expect(page.getByRole('button', { name: 'Schedule week', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Previous calendar week' }).click()
  expect(state.writes).toHaveLength(1)
})
