test('delayed old calendar response cannot overwrite the newly selected week', async ({ context, page }) => {
  let release; const held = new Promise((resolve) => { release = resolve })
  const state = await setup(context, { assignments: [
    { id: 'past', patient_profile_id: profile, routine_id: routineA, scheduled_date: '2026-10-13', status: 'scheduled', routine_name_snapshot: 'Old week snapshot' },
    { id: 'next', patient_profile_id: profile, routine_id: routineA, scheduled_date: '2026-10-27', status: 'scheduled', routine_name_snapshot: 'Next week snapshot' },
  ] }); await page.goto(path)
  await expect(page.getByRole('button', { name: 'Schedule week', exact: true })).toBeEnabled()
  state.holdRead = (start) => start === '2026-10-12' ? held : Promise.resolve()
  await page.getByRole('button', { name: 'Previous calendar week' }).click()
  await expect.poll(() => state.reads.some((url) => url.includes('2026-10-12'))).toBe(true)
  await page.getByRole('button', { name: 'Next calendar week' }).click()
  await page.getByRole('button', { name: 'Next calendar week' }).click()
  await expect(page.getByText('Next week snapshot', { exact: true })).toBeVisible()
  release()
  await page.waitForResponse((response) => response.url().includes('routine_assignments') && response.url().includes('2026-10-12'))
  await expect(page.getByText('Next week snapshot', { exact: true })).toBeVisible()
  await expect(page.getByText('Old week snapshot', { exact: true })).toHaveCount(0)
})
